//! Mapping of PKG entry IDs to canonical file names within `sce_sys`.

pub fn get_entry_name_by_type(entry_id: u32) -> Option<&'static str> {
    match entry_id {
        0x0001 => Some("digests"),
        0x0010 => Some("entry_keys"),
        0x0020 => Some("image_key"),
        0x0080 => Some("general_digests"),
        0x0100 => Some("metas"),
        0x0200 => Some("entry_names"),
        0x0400 => Some("license.dat"),
        0x0401 => Some("license.info"),
        0x0402 => Some("nptitle.dat"),
        0x0403 => Some("npbind.dat"),
        0x0404 => Some("selfinfo.dat"),
        0x0406 => Some("imageinfo.dat"),
        0x0407 => Some("target-deltainfo.dat"),
        0x0408 => Some("origin-deltainfo.dat"),
        0x0409 => Some("psreserved.dat"),
        0x1000 => Some("param.sfo"),
        0x1001 => Some("playgo-chunk.dat"),
        0x1002 => Some("playgo-chunk.sha"),
        0x1003 => Some("playgo-manifest.xml"),
        0x1004 => Some("pronunciation.xml"),
        0x1005 => Some("pronunciation.sig"),
        0x1006 => Some("pic1.png"),
        0x1007 => Some("pubtoolinfo.dat"),
        0x1008 => Some("app/playgo-chunk.dat"),
        0x1009 => Some("app/playgo-chunk.sha"),
        0x100A => Some("app/playgo-manifest.xml"),
        0x100B => Some("shareparam.json"),
        0x100C => Some("shareoverlayimage.png"),
        0x100D => Some("save_data.png"),
        0x100E => Some("shareprivacyguardimage.png"),
        0x1200 => Some("icon0.png"),
        0x1220 => Some("pic0.png"),
        0x1240 => Some("snd0.at9"),
        0x1260 => Some("changeinfo/changeinfo.xml"),
        0x1280 => Some("icon0.dds"),
        0x12A0 => Some("pic0.dds"),
        0x12C0 => Some("pic1.dds"),
        0x1400 => Some("trophy/trophy00.trp"),
        _ => None,
    }
}
